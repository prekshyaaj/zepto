# this manages the full flow between the LLM and rag this is called orchestration layer

import json

from backend.app.chatbot_model.recipe_rag.llm.openrouter import call_openrouter
from backend.app.chatbot_model.recipe_rag.rag.retriever import retrieve_products


# This prompt stays fixed for every request.
# OpenRouter creates the recipe and tells backend which ingredient names to search.
SYSTEM_PROMPT = """
You are a recipe assistant for a grocery platform.

The user will provide a dish name (may be simple, broad, or slightly unclear).

Your job:
1. If the input resembles a real food item or dish (even if broad like "pasta", "sandwich", "rice", "burger"):
   - Assume a reasonable common version of that dish.
   - Generate a complete step-by-step recipe.
   - Include exact ingredient quantities.
   - Do NOT ask for clarification for broad dishes.

2. If the input is very specific (e.g., "chicken alfredo pasta", "club sandwich"):
   - Generate recipe for that specific variant.

3. Only if the input is completely invalid, gibberish, or not related to food (e.g. "asdkjasd", "table blue running"):
   - Ask for clarification or suggest a closest possible dish.

4. Always prefer generating a recipe over asking questions.

5. Be intelligent about ambiguity:
   - "pasta" → choose a standard pasta recipe (e.g., basic tomato pasta or creamy pasta)
   - "sandwich" → default to a classic vegetable or cheese sandwich
   - "burger" → default to basic veg/non-veg burger recipe

Return ONLY valid JSON, no markdown, no extra text.

The JSON must have these keys:
{
  "needs_clarification": false,
  "clarification_message": "",
  "suggested_dish": "",
  "recipe_name": "string",
  "servings": "string",
  "ingredients": [
    {"name": "ingredient name", "quantity": "exact quantity"}
  ],
  "recipe_steps": ["numbered detailed cooking step strings"],
  "products_to_search": ["short grocery product names to search in database"]
}

For unclear gibberish input only:
{
  "needs_clarification": true,
  "clarification_message": "ask user to enter a valid dish name",
  "suggested_dish": "",
  "recipe_name": "",
  "servings": "",
  "ingredients": [],
  "recipe_steps": [],
  "products_to_search": []
}
""".strip()

#this is to clean the json text format received from llm 
def _extract_json_text(llm_text):

    cleaned_text = llm_text.strip()

    if cleaned_text.startswith("```"):
        cleaned_text = cleaned_text.strip("`")
        cleaned_text = cleaned_text.removeprefix("json").strip()

    return cleaned_text


def _safe_parse_recipe(llm_text):

    try:
        return json.loads(_extract_json_text(llm_text))   # converts cleaned JSON str from LLM into dict for backend

    except json.JSONDecodeError:   #this is fallback response if json conversion fails
        return {
            "needs_clarification": True,
            "clarification_message": "Sorry, I could not understand the recipe response. Please try entering the dish name again.",
            "suggested_dish": "",
            "recipe_name": "",
            "servings": "",
            "ingredients": [],
            "recipe_steps": [],
            "products_to_search": [],
        }


def _normalize_recipe_response(recipe_json):
    # ensures frontend always receives a fixed response structure 
    # eg: if llm forgot servings then instead of empty sevings key itll give "" so wont crash

    return {
        "needs_clarification": bool(recipe_json.get("needs_clarification", False)),
        "clarification_message": recipe_json.get("clarification_message", ""),
        "suggested_dish": recipe_json.get("suggested_dish", ""),
        "recipe_name": recipe_json.get("recipe_name", ""),
        "servings": recipe_json.get("servings", ""),
        "ingredients": recipe_json.get("ingredients", []),
        "recipe_steps": recipe_json.get("recipe_steps", []),
        "products_to_search": recipe_json.get("products_to_search", []),
    }


def _get_search_terms(recipe_json):
    # gets product names generated by LLM for database search
    return recipe_json.get("products_to_search", [])


def _add_product_links(products):
    """Attach local product links so frontend can show add-to-cart style actions."""

    linked_products = []

    for product in products:
        product_id = product.get("product_id")

        linked_product = {
            "product_id": product_id,
            "product_name": product["product_name"],
            "product_link": f"/product/{product_id}" if product_id else None,
        }

        linked_products.append(linked_product)

    return linked_products


def _match_products_for_recipe(recipe_json):
    """Search product database for every ingredient the LLM says is needed."""

    matched_products = []

    for search_term in _get_search_terms(recipe_json):  #searching for each ingredient given by llm in prod db using rag
        products = retrieve_products(search_term, k=3)  #returning top 3 similar found

        matched_products.append(
            {
                "ingredient": search_term,
                "available_products": _add_product_links(products),
            }
        )

    return matched_products


def generate_recipe(dish_name):

    user_message = f"Make a detailed recipe for: {dish_name}"

    llm_text = call_openrouter(SYSTEM_PROMPT, user_message)
    recipe_json = _normalize_recipe_response(_safe_parse_recipe(llm_text))

    #this if the dishname is not clear so we send it back to user w nearest similar dish name and to enter name again:
    if recipe_json["needs_clarification"]:  
        return {
            "dish": dish_name,
            "needs_clarification": True,
            "clarification_message": recipe_json["clarification_message"],
            "suggested_dish": recipe_json["suggested_dish"],
            "recipe": recipe_json,
            "matched_products": [],
        }

    matched_products = _match_products_for_recipe(recipe_json)

    return {
        "dish": dish_name,
        "needs_clarification": False,
        "clarification_message": "",
        "suggested_dish": "",
        "recipe": recipe_json,
        "matched_products": matched_products,
    }
